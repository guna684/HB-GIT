CREATE TABLE IF NOT EXISTS "PasswordResetOtp" (
    "Id" SERIAL PRIMARY KEY,
    "UserId" INTEGER NOT NULL,
    "OtpHash" TEXT NOT NULL,
    "ExpiresAt" TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    "FailedAttempts" INTEGER NOT NULL DEFAULT 0,
    "IsUsed" BOOLEAN NOT NULL DEFAULT FALSE,
    "CreatedAt" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT "FK_PasswordResetOtp_Users_UserId" FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "IX_PasswordResetOtp_UserId" ON "PasswordResetOtp" ("UserId");
